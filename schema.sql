-- news_collect 데이터베이스 스키마
-- psql -U postgres -d news_collect -f schema.sql
--
-- 제목 임베딩: pgvector 필요 (CREATE EXTENSION vector)
-- 모델 예: OpenAI text-embedding-3-small 등 1536차원

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS sources (
    source_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(200) NOT NULL,
    rss_url            VARCHAR(1000) UNIQUE,
    source_type        VARCHAR(20) NOT NULL
                           CHECK (source_type IN ('공식발표', '통신사', '전문미디어', '포털API', '커뮤니티')),
    credibility_weight NUMERIC(3,2) NOT NULL
                           CHECK (credibility_weight >= 0 AND credibility_weight <= 1),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS articles (
    article_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id         BIGINT NOT NULL REFERENCES sources(source_id) ON DELETE RESTRICT,
    source_url        VARCHAR(1000) NOT NULL UNIQUE,
    title             VARCHAR(500) NOT NULL,
    cleaned_content   TEXT,
    raw_content       TEXT,
    published_at      TIMESTAMPTZ,
    collected_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    status            VARCHAR(20) NOT NULL DEFAULT 'collected'
                          CHECK (status IN ('collected', 'processed', 'summarized', 'archived')),
    -- 제목 의미 벡터 (NULL 허용: 미임베딩 행). 유사 검색·중복 묶기용
    title_embedding   vector(1536)
);

CREATE INDEX IF NOT EXISTS idx_articles_source_id ON articles(source_id);
CREATE INDEX IF NOT EXISTS idx_articles_published_at ON articles(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_articles_status ON articles(status);

-- 코사인 유사도용 IVFFlat
-- lists: 대략 rows/1000 (소량 1~10, 수만 건 이상 100 근처). 데이터 늘면 REINDEX 권장
CREATE INDEX IF NOT EXISTS idx_articles_title_embedding
    ON articles
    USING ivfflat (title_embedding vector_cosine_ops)
    WITH (lists = 10);
